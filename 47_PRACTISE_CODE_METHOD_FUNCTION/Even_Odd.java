public class Even_Odd {
    public static void isEven(int n){
        if(n%2 == 0){
            System.out.println("Even");
        }
        else{
            System.out.println("Odd");
        }
            
        
    }
    public static void main(String[] args) {
        isEven(10);
        
    }
    
}
